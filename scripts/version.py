#!/usr/bin/env python3
"""Independent release versions, one source; builds never rewrite tracked files."""
import argparse
import json
import os
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
PLATFORMS = ("android", "ios", "backend", "web")
SEMVER = re.compile(r"(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\Z")
LIMITS = {"android": 2_100_000_000, "ios": 99_990_000}
IOS_CONFIG = "A83700000000000000000001"


def validate(data):
    if set(data) != {"schemaVersion", *PLATFORMS} or type(data["schemaVersion"]) is not int or data["schemaVersion"] != 1:
        raise ValueError("versions.json: unsupported schema")
    for platform in PLATFORMS:
        entry = data[platform]
        expected = {"version", "buildBase"} if platform in LIMITS else {"version"}
        if not isinstance(entry, dict) or set(entry) != expected:
            raise ValueError(f"{platform}: invalid fields")
        if not isinstance(entry["version"], str) or not SEMVER.fullmatch(entry["version"]):
            raise ValueError(f"{platform}: version must be major.minor.patch, without leading zeroes")
        if platform in LIMITS and (type(entry["buildBase"]) is not int or not 1 <= entry["buildBase"] <= LIMITS[platform]):
            raise ValueError(f"{platform}: invalid buildBase")
    return data


def read(root=ROOT):
    return validate(json.loads((root / "versions.json").read_text()))


def build_number(data, platform, run_number=None):
    if platform not in LIMITS:
        raise ValueError(f"{platform} uses version + commit, not a mobile build number")
    sequence = data[platform]["buildBase"]
    if run_number is not None:
        if not re.fullmatch(r"[1-9][0-9]*", str(run_number)):
            raise ValueError("CI run number must be a positive integer")
        sequence += int(run_number)
    if sequence > LIMITS[platform]:
        raise ValueError(f"{platform}: build number exceeds platform limit")
    if platform == "android":
        return str(sequence)
    # CFBundleVersion: first component <= 4 digits, others <= 2 digits.
    # Sequence 1 is 1.0.0 (equivalent to the original local build 1).
    sequence -= 1
    return f"{1 + sequence // 10000}.{sequence // 100 % 100}.{sequence % 100}"


def snapshots(data):
    return {
        "android/version.properties": (
            "# Generated by scripts/version.py; edit versions.json via bump.\n"
            f"versionName={data['android']['version']}\nversionCode={build_number(data, 'android')}\n"
        ),
        "ios/Version.xcconfig": (
            "// Generated by scripts/version.py; edit versions.json via bump.\n"
            f"MARKETING_VERSION = {data['ios']['version']}\nCURRENT_PROJECT_VERSION = {build_number(data, 'ios')}\n"
        ),
        "backend/internal/buildinfo/version_generated.go": (
            "// Code generated by scripts/version.py; DO NOT EDIT.\n\npackage buildinfo\n\n"
            f'const Version = "{data["backend"]["version"]}"\n'
        ),
    }


def sync(data, root=ROOT):
    for name, content in snapshots(data).items():
        path = root / name
        if path.exists() and path.read_text() == content:
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
    package = root / "web/package.json"
    manifest = json.loads(package.read_text())
    if manifest.get("version") != data["web"]["version"]:
        manifest["version"] = data["web"]["version"]
        package.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n")


def check(data, root=ROOT):
    errors = []
    if json.loads((root / "web/package.json").read_text()).get("version") != data["web"]["version"]:
        errors.append("web/package.json: out of sync; run python3 scripts/version.py sync")
    for name, content in snapshots(data).items():
        path = root / name
        if not path.is_file() or path.read_text() != content:
            errors.append(f"{name}: out of sync; run python3 scripts/version.py sync")
    project = (root / "ios/recoow.xcodeproj/project.pbxproj").read_text()
    if re.search(r"\b(?:MARKETING_VERSION|CURRENT_PROJECT_VERSION)\s*=", project):
        errors.append("iOS project overrides shared version settings")
    # Both configurations for the app and widget must consume the shared file.
    for identifier in ("3ABF80382FE1551E003C5066", "3ABF80392FE1551E003C5066", "3ABF80572FE90000003C5066", "3ABF80582FE90000003C5066"):
        if not re.search(rf"{identifier} /\* (?:Debug|Release) \*/ = \{{\s*isa = XCBuildConfiguration;\s*baseConfigurationReference = {IOS_CONFIG}\b", project):
            errors.append(f"iOS configuration {identifier} must use Version.xcconfig")
    if errors:
        raise ValueError("\n".join(errors))


def bump(data, platform, part):
    result = json.loads(json.dumps(data))
    numbers = list(map(int, result[platform]["version"].split(".")))
    index = ("major", "minor", "patch").index(part)
    numbers[index] += 1
    numbers[index + 1:] = [0] * (2 - index)
    result[platform]["version"] = ".".join(map(str, numbers))
    return validate(result)


def describe(data, platform, run_number=None):
    item = {"platform": platform, "version": data[platform]["version"], "tag": f"{platform}/v{data[platform]['version']}"}
    if platform in LIMITS:
        item["build"] = build_number(data, platform, run_number)
    return item


def commit_info(root=ROOT):
    result = subprocess.run(["git", "rev-parse", "HEAD"], cwd=root, capture_output=True, text=True)
    commit = result.stdout.strip() if result.returncode == 0 else "unknown"
    if commit != "unknown" and not re.fullmatch(r"[0-9a-f]{40,64}", commit):
        raise ValueError("invalid Git commit")
    status = subprocess.run(["git", "status", "--porcelain", "--untracked-files=normal"], cwd=root, capture_output=True, text=True)
    return commit, status.returncode != 0 or bool(status.stdout)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    show = commands.add_parser("show", help="view versions without modifying files")
    show.add_argument("platform", nargs="?", choices=PLATFORMS)
    show.add_argument("--field", choices=("version", "tag", "build"))
    show.add_argument("--run-number", help="CI workflow run number; omit for local baseline")
    commands.add_parser("check", help="validate configuration and committed generated files")
    commands.add_parser("sync", help="explicitly regenerate build files from versions.json")
    change = commands.add_parser("bump", help="manually bump one platform; no commit or tag is created")
    change.add_argument("platform", choices=PLATFORMS)
    change.add_argument("part", choices=("major", "minor", "patch"))
    ci = commands.add_parser("ci", help="check tag and print GitHub Actions output fields")
    ci.add_argument("platform", choices=PLATFORMS)
    ci.add_argument("--tag", required=True)
    ci.add_argument("--run-number", default=os.environ.get("GITHUB_RUN_NUMBER"))
    metadata = commands.add_parser("backend-metadata", help="write backend package provenance to stdout")
    args = parser.parse_args()
    try:
        data = read()
        if args.command == "check":
            check(data)
            print("Version configuration and generated files match.")
        elif args.command == "sync":
            sync(data)
        elif args.command == "bump":
            check(data)
            data = bump(data, args.platform, args.part)
            (ROOT / "versions.json").write_text(json.dumps(data, indent=2) + "\n")
            sync(data)
            print(json.dumps(describe(data, args.platform), indent=2))
        elif args.command == "show":
            if args.field and not args.platform:
                raise ValueError("--field requires a platform")
            items = [describe(data, p, args.run_number) for p in ([args.platform] if args.platform else PLATFORMS)]
            if args.field:
                if args.field not in items[0]:
                    raise ValueError(f"{args.platform} has no {args.field}")
                print(items[0][args.field])
            else:
                print(json.dumps(items[0] if args.platform else items, indent=2))
        elif args.command == "ci":
            check(data)
            if args.platform in LIMITS and args.run_number is None:
                raise ValueError("CI requires GITHUB_RUN_NUMBER or --run-number")
            item = describe(data, args.platform, args.run_number)
            if args.tag != item["tag"]:
                raise ValueError(f"tag must match versions.json: {item['tag']}")
            print("\n".join(f"{key}={value}" for key, value in item.items()))
        elif args.command == "backend-metadata":
            check(data)
            commit, dirty = commit_info()
            print(json.dumps({**describe(data, "backend"), "commit": commit, "dirty": dirty}, indent=2))
    except (ValueError, OSError) as error:
        parser.exit(1, f"version: {error}\n")


if __name__ == "__main__":
    main()
